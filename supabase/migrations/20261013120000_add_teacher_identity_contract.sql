ALTER TABLE public.users
    DROP CONSTRAINT IF EXISTS users_account_role_check;
ALTER TABLE public.users
    ADD CONSTRAINT users_account_role_check
    CHECK (
        account_role IS NULL
        OR account_role IN ('personal', 'parent', 'teacher')
    ) NOT VALID;
ALTER TABLE public.users
    VALIDATE CONSTRAINT users_account_role_check;

CREATE TABLE public.teacher_profiles (
    user_id UUID PRIMARY KEY
        REFERENCES public.users(id) ON DELETE CASCADE,
    verification_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (
            verification_status IN (
                'pending', 'verified', 'suspended', 'rejected'
            )
        ),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ,
    reviewed_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    decision_reason_code TEXT
        CHECK (
            decision_reason_code IS NULL
            OR decision_reason_code ~ '^[a-z0-9_]{1,64}$'
        ),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.teacher_profiles IS
    'Server-authoritative teacher verification. account_role alone grants no teacher privileges.';

ALTER TABLE public.teacher_profiles ENABLE ROW LEVEL SECURITY;

CREATE INDEX teacher_profiles_verification_status_idx
ON public.teacher_profiles (verification_status, requested_at);

CREATE POLICY teacher_profiles_owner_read
ON public.teacher_profiles
FOR SELECT
TO authenticated
USING ((SELECT auth.uid()) = user_id);

REVOKE ALL ON TABLE public.teacher_profiles FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.teacher_profiles TO authenticated, service_role;

CREATE TABLE private.teacher_verification_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_user_id UUID NOT NULL
        REFERENCES public.users(id) ON DELETE CASCADE,
    actor_user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    actor_role TEXT NOT NULL,
    old_status TEXT,
    new_status TEXT NOT NULL,
    reason_code TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (old_status IS NULL OR old_status IN (
        'pending', 'verified', 'suspended', 'rejected'
    )),
    CHECK (new_status IN (
        'pending', 'verified', 'suspended', 'rejected'
    )),
    CHECK (
        reason_code IS NULL
        OR reason_code ~ '^[a-z0-9_]{1,64}$'
    )
);

ALTER TABLE private.teacher_verification_events ENABLE ROW LEVEL SECURITY;
GRANT USAGE ON SCHEMA private TO service_role;
REVOKE ALL ON TABLE private.teacher_verification_events
FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE private.teacher_verification_events TO service_role;
REVOKE ALL ON SEQUENCE private.teacher_verification_events_id_seq
FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION private.record_teacher_verification_event()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_actor_role TEXT := COALESCE(
        NULLIF(current_setting('request.jwt.claim.role', true), ''),
        session_user
    );
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO private.teacher_verification_events (
            teacher_user_id,
            actor_user_id,
            actor_role,
            old_status,
            new_status,
            reason_code
        ) VALUES (
            NEW.user_id,
            (SELECT auth.uid()),
            v_actor_role,
            NULL,
            NEW.verification_status,
            NEW.decision_reason_code
        );
    ELSIF OLD.verification_status IS DISTINCT FROM NEW.verification_status
       OR OLD.decision_reason_code IS DISTINCT FROM NEW.decision_reason_code THEN
        INSERT INTO private.teacher_verification_events (
            teacher_user_id,
            actor_user_id,
            actor_role,
            old_status,
            new_status,
            reason_code
        ) VALUES (
            NEW.user_id,
            (SELECT auth.uid()),
            v_actor_role,
            OLD.verification_status,
            NEW.verification_status,
            NEW.decision_reason_code
        );
    END IF;
    RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION private.record_teacher_verification_event()
FROM PUBLIC, anon, authenticated;

CREATE TRIGGER record_teacher_verification_event
AFTER INSERT OR UPDATE OF verification_status
ON public.teacher_profiles
FOR EACH ROW
EXECUTE FUNCTION private.record_teacher_verification_event();

CREATE OR REPLACE FUNCTION private.sync_teacher_profile_from_role()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF NEW.account_role = 'teacher' THEN
        INSERT INTO public.teacher_profiles (user_id)
        VALUES (NEW.id)
        ON CONFLICT (user_id) DO NOTHING;
    END IF;
    RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION private.sync_teacher_profile_from_role()
FROM PUBLIC, anon, authenticated;

CREATE TRIGGER sync_teacher_profile_from_role
AFTER INSERT OR UPDATE OF account_role
ON public.users
FOR EACH ROW
WHEN (NEW.account_role = 'teacher')
EXECUTE FUNCTION private.sync_teacher_profile_from_role();

INSERT INTO public.teacher_profiles (user_id)
SELECT id
FROM public.users
WHERE account_role = 'teacher'
ON CONFLICT (user_id) DO NOTHING;

CREATE OR REPLACE FUNCTION private.is_verified_teacher(p_user_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.users AS u
        JOIN public.teacher_profiles AS tp ON tp.user_id = u.id
        WHERE u.id = p_user_id
          AND u.account_role = 'teacher'
          AND tp.verification_status = 'verified'
    );
$$;

REVOKE ALL ON FUNCTION private.is_verified_teacher(UUID)
FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.is_current_user_verified_teacher()
